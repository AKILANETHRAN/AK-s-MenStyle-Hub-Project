-- PostgreSQL application schema. No customer records or seed data.
CREATE TABLE IF NOT EXISTS "products" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    brand TEXT,
    category TEXT NOT NULL,
    cloth_type TEXT,
    color TEXT,
    price DOUBLE PRECISION NOT NULL CHECK(price <= 700 AND price >= 400),
    original_price DOUBLE PRECISION NOT NULL CHECK(original_price >= price),
    discount_percent DOUBLE PRECISION DEFAULT 0 CHECK(discount_percent >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0),
    status TEXT NOT NULL DEFAULT 'IN_STOCK' CHECK(status IN ('IN_STOCK', 'SOLD_OUT')),
    image TEXT,
    garment_image TEXT,
    vton_supported INTEGER DEFAULT 0 CHECK(vton_supported IN (0, 1)),
    vton_garment_category TEXT CHECK(vton_garment_category IN ('tops', 'bottoms') OR vton_garment_category IS NULL),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
  , is_new_arrival INTEGER NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS outfit_recommendations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        base_product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        recommended_product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        slot_type TEXT NOT NULL,
        reason TEXT,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      , combination_signature TEXT);

CREATE TABLE IF NOT EXISTS "users" (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          username TEXT UNIQUE,
          full_name TEXT NOT NULL,
          email TEXT NOT NULL UNIQUE,
          password_hash TEXT NOT NULL,
          role TEXT NOT NULL DEFAULT 'USER' CHECK(role IN ('USER', 'ADMIN')),
          phone TEXT,
          age INTEGER,
          address TEXT,
          city TEXT,
          state TEXT,
          pincode TEXT,
          created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          google_id TEXT,
          avatar_url TEXT,
          email_notifications INTEGER NOT NULL DEFAULT 1,
          sms_notifications INTEGER NOT NULL DEFAULT 1,
          whatsapp_notifications INTEGER NOT NULL DEFAULT 1,
          theme_preference TEXT NOT NULL DEFAULT 'gold-silver',
          language_preference TEXT NOT NULL DEFAULT 'en'
        );

CREATE TABLE IF NOT EXISTS cart (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      );

CREATE TABLE IF NOT EXISTS wishlists (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      );

CREATE TABLE IF NOT EXISTS wishlist_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        wishlist_id INTEGER NOT NULL REFERENCES wishlists(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(wishlist_id, product_id)
      );

CREATE TABLE IF NOT EXISTS friendships (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        requester_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        receiver_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        status TEXT NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        CHECK(requester_id != receiver_id),
        UNIQUE(requester_id, receiver_id)
      );

CREATE TABLE IF NOT EXISTS orders (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_number TEXT NOT NULL UNIQUE,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        status TEXT NOT NULL DEFAULT 'PLACED' CHECK(status IN ('PLACED', 'CONFIRMED', 'SHIPPED', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED')),
        subtotal DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(subtotal >= 0),
        discount_total DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(discount_total >= 0),
        shipping_fee DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(shipping_fee >= 0),
        other_charges DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(other_charges >= 0),
        total_amount DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(total_amount >= 0),
        delivery_address TEXT NOT NULL,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        delivery_date TIMESTAMP WITHOUT TIME ZONE,
        cancelled_at TIMESTAMP WITHOUT TIME ZONE
      );

CREATE TABLE IF NOT EXISTS order_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id),
        product_name TEXT NOT NULL,
        product_image TEXT,
        quantity INTEGER NOT NULL CHECK(quantity > 0),
        unit_price DOUBLE PRECISION NOT NULL CHECK(unit_price >= 0),
        discount DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(discount >= 0),
        final_price DOUBLE PRECISION NOT NULL CHECK(final_price >= 0)
      , size TEXT CHECK(size IN ('S', 'M', 'L', 'XL', 'XXL') OR size IS NULL));

CREATE TABLE IF NOT EXISTS notifications (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        type TEXT NOT NULL,
        title TEXT NOT NULL,
        message TEXT NOT NULL,
        is_read INTEGER NOT NULL DEFAULT 0 CHECK(is_read IN (0, 1)),
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      , related_id INTEGER);

CREATE TABLE IF NOT EXISTS try_on_results (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        user_image_path TEXT NOT NULL,
        garment_image_path TEXT NOT NULL,
        generated_image_path TEXT,
        category TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'PROCESSING' CHECK(status IN ('PROCESSING', 'COMPLETED', 'FAILED')),
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      );

CREATE TABLE IF NOT EXISTS purchases (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        purchase_type TEXT NOT NULL CHECK(purchase_type IN ('SINGLE', 'COMBO')),
        total_amount DOUBLE PRECISION NOT NULL CHECK(total_amount >= 0),
        delivery_name TEXT NOT NULL,
        delivery_phone TEXT NOT NULL,
        delivery_address TEXT NOT NULL,
        delivery_city TEXT NOT NULL,
        delivery_state TEXT NOT NULL,
        delivery_pincode TEXT NOT NULL,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      , cart_reward_percent DOUBLE PRECISION DEFAULT 0, cart_reward_amount DOUBLE PRECISION DEFAULT 0, subtotal DOUBLE PRECISION);

CREATE TABLE IF NOT EXISTS purchase_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        purchase_id INTEGER NOT NULL REFERENCES purchases(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id),
        quantity INTEGER NOT NULL CHECK(quantity > 0),
        unit_price DOUBLE PRECISION NOT NULL CHECK(unit_price >= 0),
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      , size TEXT CHECK(size IN ('S', 'M', 'L', 'XL', 'XXL') OR size IS NULL));

CREATE TABLE IF NOT EXISTS "wishlist_shares" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    receiver_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    wishlist_id INTEGER REFERENCES wishlists(id) ON DELETE CASCADE,
    share_type TEXT DEFAULT 'PRODUCTS',
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
  );

CREATE TABLE IF NOT EXISTS wishlist_feedback (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        share_id INTEGER NOT NULL REFERENCES wishlist_shares(id) ON DELETE CASCADE,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        reaction TEXT CHECK(reaction IN ('LIKE', 'LOVE', 'FIRE') OR reaction IS NULL),
        comment TEXT,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      );

CREATE TABLE IF NOT EXISTS wishlist_share_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        share_id INTEGER NOT NULL REFERENCES wishlist_shares(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(share_id, product_id)
      );

CREATE TABLE IF NOT EXISTS recently_accessed (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
        accessed_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        UNIQUE(user_id, product_id)
      );

CREATE TABLE IF NOT EXISTS "notification_deliveries" (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          purchase_id INTEGER NOT NULL REFERENCES purchases(id) ON DELETE CASCADE,
          user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          channel TEXT NOT NULL CHECK(channel IN ('EMAIL', 'SMS', 'WHATSAPP')),
          status TEXT NOT NULL CHECK(status IN ('PENDING', 'SENT', 'FAILED', 'NOT_CONFIGURED', 'DISABLED', 'SIMULATED')),
          recipient TEXT,
          provider_message_id TEXT,
          error_message TEXT,
          event_type TEXT DEFAULT 'PURCHASE_SUCCESS',
          subject TEXT,
          created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
        );

CREATE TABLE IF NOT EXISTS "cart_items" (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          cart_id INTEGER NOT NULL REFERENCES cart(id) ON DELETE CASCADE,
          product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
          size TEXT CHECK(size IN ('S', 'M', 'L', 'XL', 'XXL') OR size IS NULL),
          quantity INTEGER NOT NULL CHECK(quantity > 0),
          created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
          updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
        );

CREATE TABLE IF NOT EXISTS whatsapp_event_deliveries (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
        event_type TEXT NOT NULL CHECK(event_type IN ('DISCOUNT_ALERT', 'NEW_ARRIVAL')),
        recipient TEXT NOT NULL,
        status TEXT NOT NULL CHECK(status IN ('SENT', 'FAILED', 'NOT_CONFIGURED', 'DISABLED')),
        provider_message_id TEXT,
        error_message TEXT,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
      );

CREATE TABLE IF NOT EXISTS message_templates (
        channel TEXT PRIMARY KEY CHECK(channel IN ('EMAIL', 'SMS', 'WHATSAPP')),
        body TEXT NOT NULL,
        updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
        updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
      );

CREATE INDEX IF NOT EXISTS idx_cart_user_id ON cart(user_id);
CREATE INDEX IF NOT EXISTS idx_wishlist_items_wishlist_id ON wishlist_items(wishlist_id);
CREATE INDEX IF NOT EXISTS idx_friendships_requester_id ON friendships(requester_id);
CREATE INDEX IF NOT EXISTS idx_friendships_receiver_id ON friendships(receiver_id);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_notifications_user_id ON notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_try_on_results_user_id ON try_on_results(user_id);
CREATE INDEX IF NOT EXISTS idx_purchases_user_id ON purchases(user_id);
CREATE INDEX IF NOT EXISTS idx_purchase_items_purchase_id ON purchase_items(purchase_id);
CREATE INDEX IF NOT EXISTS idx_outfit_recs_signature ON outfit_recommendations(combination_signature);
CREATE INDEX IF NOT EXISTS idx_outfit_recs_base ON outfit_recommendations(base_product_id);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_color ON products(color);
CREATE INDEX IF NOT EXISTS idx_products_stock ON products(stock);
CREATE INDEX IF NOT EXISTS idx_recently_accessed_user_date ON recently_accessed(user_id, accessed_at DESC);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_username ON users(username);
CREATE INDEX IF NOT EXISTS idx_notif_deliveries_purchase ON notification_deliveries(purchase_id);
CREATE INDEX IF NOT EXISTS idx_notif_deliveries_user ON notification_deliveries(user_id);
CREATE INDEX IF NOT EXISTS idx_cart_items_cart_id ON cart_items(cart_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_cart_items_clothing ON cart_items(cart_id, product_id, size) WHERE size IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_cart_items_accessory ON cart_items(cart_id, product_id) WHERE size IS NULL;
CREATE INDEX IF NOT EXISTS idx_whatsapp_event_deliveries_product ON whatsapp_event_deliveries(product_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_lower ON users(LOWER(username));
